})

test_that('raise-only iteration never lowers a retained parameter', {
 fit<-list(status='fitted',interval=rbind(Dropout=c(lower=.02,upper=.03),Foreign=c(lower=.001,upper=.002)))
 a<-.parentage_error_iteration_step(fit,c(Dropout=.01,Foreign=.01),c(Dropout=0,Foreign=0),1L,'raise_only')
 expect_equal(a$next_rates,c(Dropout=.02,Foreign=.01));expect_true(a$continue)
 b<-.parentage_error_iteration_step(fit,a$next_rates,a$previous_direction,2L,'raise_only')
 expect_false(b$continue);expect_equal(b$next_rates,a$next_rates)
 a<-.parentage_error_iteration_step(fit,c(Dropout=.01,Foreign=.01),c(Dropout=1,Foreign=0),4L,'raise_only')
 expect_false(a$continue);expect_identical(a$stop_reason,'maximum_searches')
})

test_that('combined policy raises repeatedly but lowers only on the original fit', {
  fit <- list(status='fitted',interval=rbind(Dropout=c(lower=.02,upper=.04),Foreign=c(lower=.001,upper=.003)))
  current <- c(Dropout=.01,Foreign=.02)
  a <- .parentage_error_raise_guarded_step(fit,current,70,100,1L)
  expect_true(a$continue)
  expect_equal(a$next_rates,c(Dropout=.02,Foreign=.02))
  expect_true(a$proposal$raise); expect_false(a$proposal$lower)
  expect_equal(a$proposal$upper_95,c(Dropout=.04,Foreign=.003))
  weak <- .parentage_error_raise_guarded_step(fit,current,69,100,1L)
  expect_equal(weak$next_rates,c(Dropout=.02,Foreign=.02))
  second <- .parentage_error_raise_guarded_step(fit,current,100,100,2L)
  expect_equal(second$next_rates,c(Dropout=.02,Foreign=.02))
  retained <- .parentage_error_raise_guarded_step(fit,a$next_rates,100,100,2L)
  expect_false(retained$continue)
  fit$interval['Dropout','lower'] <- .03
  raised <- .parentage_error_raise_guarded_step(fit,a$next_rates,100,100,2L)
  expect_equal(raised$next_rates,c(Dropout=.03,Foreign=.02))
  expect_identical(.parentage_error_raise_guarded_step(fit,a$next_rates,100,100,4L)$stop_reason,'maximum_searches')
  snp <- list(status='fitted',interval=c(lower=.001,upper=.003))
  expect_equal(.parentage_error_raise_guarded_step(snp,c(Err=.02),70,100,1L)$next_rates,c(Err=.003))
  expect_false(.parentage_error_raise_guarded_step(snp,c(Err=.003),70,100,2L)$continue)
  expect_false(.parentage_error_raise_guarded_step(list(status='too_few_trios'),c(Err=.02),0,0,1L)$continue)
})

test_that('guarded decisions retain the strict factor-two trigger but target the upper bound', {
  fit <- list(status='fitted',interval=c(lower=.001,upper=.02))
  step <- .parentage_guarded_lower_step(fit,c(Err=.1),70,100,1L)
  expect_identical(step$proposal$status,'lowered_to_upper_bound')
  expect_equal(step$proposal$used_rate,.02)
  expect_equal(step$proposal$upper_95,.02)
  mh <- list(status='fitted',interval=rbind(Dropout=c(lower=.001,upper=.02),Foreign=c(lower=.001,upper=.004)))
  step <- .parentage_guarded_lower_step(mh,c(Dropout=.1,Foreign=.005),70,100,1L)
  expect_identical(step$proposal$parameters$Dropout$status,'lowered_to_upper_bound')
  expect_identical(step$proposal$parameters$Foreign$status,'supplied_foreign_retained')
})
