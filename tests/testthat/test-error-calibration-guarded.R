test_that('guarded lowering requires strict factor-two and inclusive cohort guards', {
 fit<-list(status='fitted',interval=c(lower=.001,upper=.02))
 run<-function(rate=.1,n=70,pass=1L).parentage_guarded_lower_step(fit,c(Err=rate),n,100,pass)
 a<-run();expect_true(a$continue);expect_equal(a$next_rates,c(Err=.02))
 expect_false(run(n=69)$continue)
 expect_identical(run(n=69)$stop_reason,'insufficient_confident_fraction')
 expect_false(run(rate=.04)$continue);expect_false(run(rate=.03)$continue)
 expect_false(run(pass=2L)$continue)
 expect_identical(run(pass=2L)$stop_reason,'guarded_lowering_completed')
 expect_false(.parentage_guarded_lower_step(fit,c(Err=.1),0,0,1)$continue)
})

test_that('guarded multiallelic lowering adjusts only Dropout', {
 fit<-list(status='fitted',interval=rbind(Dropout=c(lower=.001,upper=.02),Foreign=c(lower=.001,upper=.004)))
 a<-.parentage_guarded_lower_step(fit,c(Dropout=.1,Foreign=.005),80,100,1L)
